#!/usr/bin/env python3
"""Regenerate `shared/src/font8x16.rs` from a BDF font.

    python3 tools/gen-font8x16.py /path/to/spleen-8x16.bdf > shared/src/font8x16.rs

Only printable ASCII (0x20..0x7E) is extracted: that is all the boot console
prints. Every glyph must be exactly 8x16 at offset (0, -4), so the converter
fails loudly rather than silently mangling a font that has different metrics.

The font currently vendored is Spleen 8x16 (BSD-2-Clause, Frederic Cambus,
https://github.com/fcambus/spleen). See deps.md.
"""

import re
import sys

FIRST = 0x20
LAST = 0x7E


def main(path: str) -> None:
    text = open(path, encoding="utf-8").read()
    blocks = re.findall(r"STARTCHAR.*?ENDCHAR", text, re.S)
    glyphs = {}
    for block in blocks:
        enc = int(re.search(r"ENCODING (-?\d+)", block).group(1))
        if not FIRST <= enc <= LAST:
            continue
        bbx = re.search(r"BBX (\S+) (\S+) (\S+) (\S+)", block).groups()
        if bbx != ("8", "16", "0", "-4"):
            sys.exit(f"glyph {enc:#x} has BBX {bbx}, expected 8 16 0 -4")
        bitmap = re.search(r"BITMAP(.*?)ENDCHAR", block, re.S).group(1)
        rows = [r.strip() for r in bitmap.strip().splitlines() if r.strip()]
        if len(rows) != 16:
            sys.exit(f"glyph {enc:#x} has {len(rows)} bitmap rows, expected 16")
        glyphs[enc] = bytes(int(r, 16) for r in rows)

    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        sys.exit(f"font is missing printable ASCII: {missing}")

    out = []
    out.append("//! 8x16 bitmap font for the on-screen boot console.")
    out.append("//!")
    out.append("//! Generated by `tools/gen-font8x16.py` from **Spleen 8x16**")
    out.append("//! (Copyright (c) 2018-2026, Frederic Cambus), released under the")
    out.append("//! BSD 2-Clause licence: https://github.com/fcambus/spleen")
    out.append("//! See `deps.md` for the vendoring record. Do not edit by hand.")
    out.append("//!")
    out.append("//! One glyph is 16 bytes, one byte per row, bit 7 = leftmost pixel,")
    out.append("//! covering printable ASCII 0x20..=0x7E.")
    out.append("")
    out.append("/// Width of one glyph cell in pixels.")
    out.append("pub const GLYPH_WIDTH: usize = 8;")
    out.append("/// Height of one glyph cell in pixels.")
    out.append("pub const GLYPH_HEIGHT: usize = 16;")
    out.append("/// First character code covered by [`GLYPHS`].")
    out.append("pub const FIRST_CHAR: u8 = 0x20;")
    out.append("/// Last character code covered by [`GLYPHS`].")
    out.append("pub const LAST_CHAR: u8 = 0x7E;")
    out.append("")
    out.append("/// One entry per character from `FIRST_CHAR` to `LAST_CHAR`.")
    out.append("pub static GLYPHS: [[u8; GLYPH_HEIGHT]; (LAST_CHAR - FIRST_CHAR + 1) as usize] = [")
    for c in range(FIRST, LAST + 1):
        g = glyphs[c]
        ch = chr(c)
        label = "space" if c == 0x20 else ch
        rows = ", ".join(f"0x{b:02x}" for b in g)
        out.append(f"    [{rows}], // 0x{c:02x} {label}")
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
